def calculate_turbine_fuel(p_start=10, p_end=100, p_step=10):
    """
    Функция рассчитывает суммарный расход топлива турбины в заданном диапазоне нагрузок.
    Параметры:
    p_start (int/float): Начальная нагрузка (МВт)
    p_end (int/float): Конечная нагрузка (МВт)
    p_step (int/float): Шаг изменения нагрузки (МВт)

    """
    total_fuel = 0.0 #Создание переменной для общего кол-ва расхода топлива 
    # Цикл for перебирает нагрузки от 10 до 100 с шагом 10
    for P in range(p_start, p_end + 1, p_step):
        #Рассчитываем удельный расход по диапозону нагрузок
        if P < 40:    # Мвт
            q = 0.25  # кг/кВт*ч
        else:
            q = 0.21  # кг/кВт*ч
        # Рассчитываем расход топлива для текущей нагрузки (В МВт * 1000 = кВт)
        current_fuel = P * 1000 * q
        # Добавляем расход текущей нагрузки к  общщему
        total_fuel += current_fuel
        # Вывод расхода для конкретной нагрузки
        print(f"Нагрузка P = {P} МВт; Удельный расход q = {q} кг/кВт*ч. Расход: {current_fuel:.2f} кг")
    # Возвращаем суммарный расход топлива
    return total_fuel
#Tестирование функции
print("Расчет суммарного расхода топлива турбины:")
# Вызываем функцию и сохраняем результат в переменную
result = calculate_turbine_fuel()
print(f"Суммарный расход топлива за весь цикл: {result:.2f} кг")
