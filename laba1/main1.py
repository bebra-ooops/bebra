#Ввод данных, команда input()
# Функция float() принимает дробное число
m = float(input("введите массу:m= "))
k = float(input("введите жесткость пружины:k= "))
pi = 3.14159 # Обозначаем константу, чтобы пользователь не вводил ее самостоятельно.
T = 2*pi*(m/k)**(1/2) #Программа подставляет значения в формулу, происходит вычисление
# Конструкция {T:.4f} выводит переменную T как число, округлив его до 4 знаков после запятой.
# Для вывода данных на экран используется команда print()
print(f"Период колебаний пружинного маятника T = {T:.4f}")
